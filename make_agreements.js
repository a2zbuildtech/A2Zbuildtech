const t = (text, o) => new TextRun(Object.assign({ text, font: FONT, size: 22, color: INK }, o || {}));
function runs(x, o) { return String(x).split(/(\*\*[^*]+\*\*)/).filter(Boolean).map((s) => s.startsWith('**') ? t(s.slice(2, -2), Object.assign({ bold: true }, o || {})) : t(s, o)); }

function Builder() {
  const kids = []; let n = 0;
  const api = {
    kids,
    title(main, sub) {
      kids.push(new Paragraph({ alignment: AlignmentType.CENTER, spacing: { after: 40 }, children: [t(FIRM, { bold: true, size: 26, color: STEEL })] }));
      kids.push(new Paragraph({ alignment: AlignmentType.CENTER, spacing: { after: 160 }, children: [t(ADDR, { size: 19, color: MUTE })] }));
      kids.push(new Paragraph({ alignment: AlignmentType.CENTER, spacing: { before: 120, after: 60 }, border: { top: { style: BorderStyle.SINGLE, size: 8, color: STEEL, space: 8 }, bottom: { style: BorderStyle.SINGLE, size: 8, color: STEEL, space: 8 } }, children: [t(main, { bold: true, size: 34 })] }));
      if (sub) kids.push(new Paragraph({ alignment: AlignmentType.CENTER, spacing: { before: 60, after: 200 }, children: [t(sub, { size: 20, color: MUTE })] }));
    },
    p(x, o) { kids.push(new Paragraph({ alignment: AlignmentType.JUSTIFIED, spacing: { after: 110, line: 300 }, indent: o && o.indent ? { left: o.indent } : undefined, children: runs(x) })); },
    h(x) { kids.push(new Paragraph({ keepNext: true, spacing: { before: 220, after: 100 }, children: [t(x, { bold: true, size: 24, color: STEEL })] })); },
    clause(title, items) {
      n++;
      kids.push(new Paragraph({ keepNext: true, spacing: { before: 200, after: 80 }, children: [t(n + '.  ' + title, { bold: true, size: 23 })] }));
      items.forEach((x, i) => kids.push(new Paragraph({ alignment: AlignmentType.JUSTIFIED, spacing: { after: 90, line: 296 }, indent: { left: 520, hanging: 520 }, children: [t(n + '.' + (i + 1) + '   ')].concat(runs(x)) })));
    },
    note(label, x) { kids.push(new Paragraph({ spacing: { before: 120, after: 160, line: 290 }, indent: { left: 200 }, border: { left: { style: BorderStyle.SINGLE, size: 18, color: STEEL, space: 8 } }, shading: { type: ShadingType.CLEAR, fill: SOFT }, children: [t(label + ' ', { bold: true, color: STEEL })].concat(runs(x)) })); },
    sp() { kids.push(new Paragraph({ spacing: { after: 100 }, children: [] })); },
    pb() { kids.push(new Paragraph({ children: [new PageBreak()] })); },
    table(head, rows, widths, o) {
      o = o || {}; const bd = { style: BorderStyle.SINGLE, size: 4, color: LINE }; const borders = { top: bd, bottom: bd, left: bd, right: bd };
      const cell = (x, w, hdr, right) => new TableCell({ width: { size: w, type: WidthType.DXA }, borders, shading: hdr ? { type: ShadingType.CLEAR, fill: SOFT } : undefined, margins: { top: o.tall ? 130 : 70, bottom: o.tall ? 130 : 70, left: 100, right: 100 }, children: [new Paragraph({ alignment: right ? AlignmentType.RIGHT : AlignmentType.LEFT, spacing: { after: 0, line: 264 }, children: hdr ? [t(String(x), { bold: true, size: 20 })] : runs(x, { size: 21 }) })] });
      const out = [];
      if (head) out.push(new TableRow({ tableHeader: true, children: head.map((h, i) => cell(h, widths[i], true, o.right && o.right.includes(i))) }));
      rows.forEach((r) => out.push(new TableRow({ cantSplit: true, children: r.map((c, i) => cell(c, widths[i], false, o.right && o.right.includes(i))) })));
      kids.push(new Table({ width: { size: widths.reduce((a, b) => a + b, 0), type: WidthType.DXA }, columnWidths: widths, rows: out }));
      api.sp();
    },
    /* "label : ______" rows used for filling in details */
    fields(rows, w) { w = w || [3000, 6026]; api.table(null, rows.map((r) => [r, B(34)]), w, { tall: true }); },
    sign(leftTitle, leftLines, rightTitle, rightLines) {
      const box = (title, lines) => new TableCell({ width: { size: 4513, type: WidthType.DXA }, borders: { top: { style: BorderStyle.NONE }, bottom: { style: BorderStyle.NONE }, left: { style: BorderStyle.NONE }, right: { style: BorderStyle.NONE } }, margins: { top: 60, bottom: 60, left: 80, right: 80 }, children: [new Paragraph({ spacing: { after: 60 }, children: [t(title, { bold: true })] }), new Paragraph({ spacing: { before: 520, after: 40 }, children: [t(B(30))] })].concat(lines.map((l) => new Paragraph({ spacing: { after: 30 }, children: [t(l, { size: 20 })] }))) });
      kids.push(new Table({ width: { size: 9026, type: WidthType.DXA }, columnWidths: [4513, 4513], rows: [new TableRow({ cantSplit: true, children: [box(leftTitle, leftLines), box(rightTitle, rightLines)] })] }));
      api.sp();
    },
    witnesses() {
      api.h('गवाह (Witnesses)');
      api.table(['क्र.', 'नाम व पिता / पति का नाम', 'पता व मोबाइल', 'हस्ताक्षर'], [['1', '', '', ''], ['2', '', '', '']], [600, 3000, 3200, 2226], { tall: true });
    },
    lastPage(extra) {
      api.pb();
      api.h('उपयोग से पहले ज़रूरी बातें (इस पेज को अंतिम प्रति में हटा दें)');
      const base = [
        'यह **मसौदा (draft)** है, तैयार वकील-सलाह नहीं है। हस्ताक्षर से पहले अपने वकील / CA से ज़रूर जँचवाएँ।',
        'सही **स्टाम्प पेपर** (मध्य प्रदेश में लागू राशि का) पर छपवाएँ, सभी पन्नों पर दोनों पक्ष **संक्षिप्त हस्ताक्षर (initial)** करें, और ज़रूरत हो तो नोटरी / पंजीयन कराएँ।',
        'खाली जगह (____) हाथ से या कंप्यूटर पर भरें। ☐ वाले विकल्प में से जो लागू हो उस पर निशान लगाएँ और बाकी काट दें।',
        'फर्म का कानूनी रूप (proprietorship / partnership / LLP / कंपनी), PAN, GSTIN, श्रम-ठेकेदार लाइसेंस, EPF व ESIC पंजीयन की जानकारी सही-सही भरें।',
        'GST, TDS, PF/ESIC, न्यूनतम मज़दूरी और स्टाम्प ड्यूटी के नियम समय-समय पर बदलते हैं; लागू दरें CA / वकील से पक्की कर लें।'
      ].concat(extra || []);
      base.forEach((x) => api.p('•  ' + x));
    }
  };
  return api;
}

function save(name, b, short) {
  const doc = new Document({
    creator: 'A2Z Build Tech', title: short,
    styles: { default: { document: { run: { font: FONT, size: 22 } } } },
    sections: [{
      properties: { page: { size: { width: 11906, height: 16838 }, margin: { top: 1300, bottom: 1200, left: 1440, right: 1440 } } },
      headers: { default: new Header({ children: [new Paragraph({ alignment: AlignmentType.RIGHT, children: [t(short + '  |  ' + FIRM, { size: 17, color: MUTE })] })] }) },
      footers: { default: new Footer({ children: [new Paragraph({ alignment: AlignmentType.CENTER, children: [t('पृष्ठ ', { size: 17, color: MUTE }), new TextRun({ children: [PageNumber.CURRENT], font: FONT, size: 17, color: MUTE }), t(' / ', { size: 17, color: MUTE }), new TextRun({ children: [PageNumber.TOTAL_PAGES], font: FONT, size: 17, color: MUTE }), t('        पक्ष-1 संक्षिप्त हस्ताक्षर: ______      पक्ष-2 संक्षिप्त हस्ताक्षर: ______', { size: 17, color: MUTE })] })] }) },
      children: b.kids
    }]
  });
  return Packer.toBuffer(doc).then((buf) => { fs.writeFileSync(path.join(OUT, name), buf); console.log('wrote', name, Math.round(buf.length / 1024) + ' KB'); });
}

