function TBL(head, rows, widths, opt) {
  opt = opt || {};
  const total = widths.reduce((a, b) => a + b, 0);
  const bd = { style: BorderStyle.SINGLE, size: 4, color: LINE };
  const borders = { top: bd, bottom: bd, left: bd, right: bd };
  const cell = (t, w, hdr, right) => new TableCell({
    width: { size: w, type: WidthType.DXA }, borders,
    shading: hdr ? { type: ShadingType.CLEAR, fill: SOFT } : undefined,
    margins: { top: 60, bottom: 60, left: 100, right: 100 },
    children: [new Paragraph({ alignment: right ? AlignmentType.RIGHT : AlignmentType.LEFT, spacing: { after: 0, line: 264 }, children: hdr ? [run1(String(t), { bold: true, size: 20 })] : runs(t).map(r => r) })]
  });
  const rowsOut = [new TableRow({ tableHeader: true, children: head.map((h, i) => cell(h, widths[i], true, opt.right && opt.right.includes(i))) })]
    .concat(rows.map(r => new TableRow({ cantSplit: true, children: r.map((c, i) => cell(c, widths[i], false, opt.right && opt.right.includes(i))) })));
  kids.push(new Table({ width: { size: total, type: WidthType.DXA }, columnWidths: widths, rows: rowsOut }));
  SP();
}
